export function getDeweyForCategory(category: string | null | undefined): string {
  if (!category) return "000";
  const key = category.trim().toLowerCase();
  if (!key) return "000";
  if (EXACT_MAP[key]) return EXACT_MAP[key];
  for (const [re, code] of KEYWORD_MAP) {
    if (re.test(key)) return code;
  }
  return "000";
}
